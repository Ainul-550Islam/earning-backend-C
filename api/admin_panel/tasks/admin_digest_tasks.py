# api/admin_panel/tasks/admin_digest_tasks.py
"""
Daily admin digest email task.
Sends a summary of platform activity to all superadmin users each morning.
CPAlead-style: users, revenue, withdrawals, fraud alerts, insights.
"""
import logging
from celery import shared_task
from django.utils import timezone
from datetime import timedelta

logger = logging.getLogger(__name__)


def send_digest():
    """Build and send daily admin digest to all superadmin users."""
    try:
        from django.contrib.auth import get_user_model
        User = get_user_model()

        admins = User.objects.filter(
            is_superuser=True, is_active=True
        ).exclude(email='')
        emails = list(admins.values_list('email', flat=True))

        if not emails:
            logger.info("No superadmin emails found for digest.")
            return {'sent': 0}

        stats = _build_digest_stats()
        subject, body = _format_digest(stats)

        from ..utils import send_admin_email_notification
        send_admin_email_notification(subject, body, emails)

        logger.info(f"Admin digest sent to {len(emails)} admins.")
        return {'sent': len(emails), 'stats': stats}

    except Exception as e:
        logger.error(f"Admin digest task failed: {e}")
        return {'error': str(e)}


def _build_digest_stats() -> dict:
    """Gather all stats for the digest."""
    from django.utils import timezone
    from datetime import timedelta
    today = timezone.now().date()
    yesterday = today - timedelta(days=1)
    stats = {'date': str(yesterday)}

    # Users
    try:
        from django.contrib.auth import get_user_model
        User = get_user_model()
        stats['new_users'] = User.objects.filter(date_joined__date=yesterday).count()
        stats['total_users'] = User.objects.count()
        stats['active_users'] = User.objects.filter(is_active=True).count()
    except Exception:
        stats['new_users'] = 'N/A'

    # Revenue
    try:
        from api.transactions.models import Transaction
        from django.db.models import Sum
        rev = Transaction.objects.filter(
            transaction_type='earning', status='completed', created_at__date=yesterday
        ).aggregate(total=Sum('gross_amount'))['total'] or 0
        stats['revenue'] = float(rev)
    except Exception:
        stats['revenue'] = 'N/A'

    # Withdrawals
    try:
        from api.withdrawals.models import Withdrawal
        from django.db.models import Sum, Count
        wd = Withdrawal.objects.filter(
            created_at__date=yesterday
        ).aggregate(count=Count('id'), total=Sum('gross_amount'))
        stats['withdrawal_requests'] = wd.get('count') or 0
        stats['withdrawal_amount'] = float(wd.get('total') or 0)
        stats['pending_withdrawals'] = Withdrawal.objects.filter(status='QUEUED').count()
    except Exception:
        stats['withdrawal_requests'] = 'N/A'
        stats['pending_withdrawals'] = 'N/A'

    # Admin activity
    try:
        from ..models.activity import AdminActivity
        stats['admin_actions'] = AdminActivity.objects.filter(
            created_at__date=yesterday
        ).count()
    except Exception:
        stats['admin_actions'] = 'N/A'

    # Insights
    try:
        from ..models.reports import AdminInsight
        critical_insights = AdminInsight.objects.filter(
            priority='critical',
            is_dismissed=False,
            created_at__date=yesterday,
        ).values_list('title', flat=True)[:5]
        stats['critical_insights'] = list(critical_insights)
    except Exception:
        stats['critical_insights'] = []

    return stats


def _format_digest(stats: dict) -> tuple:
    """Format digest subject and body."""
    date_str = stats.get('date', 'Yesterday')
    subject = f"[Admin Digest] Platform Summary for {date_str}"
    body = f"""
Daily Admin Digest — {date_str}
{'=' * 50}

👥 USERS
  New Registrations:  {stats.get('new_users', 'N/A')}
  Total Users:        {stats.get('total_users', 'N/A')}
  Active Users:       {stats.get('active_users', 'N/A')}

💰 REVENUE
  Yesterday Revenue:  ৳{stats.get('revenue', 0):,}

💳 WITHDRAWALS
  New Requests:       {stats.get('withdrawal_requests', 'N/A')}
  Amount:             ৳{stats.get('withdrawal_amount', 0):,.2f}
  Pending (total):    {stats.get('pending_withdrawals', 'N/A')}

⚙️ ADMIN ACTIVITY
  Admin Actions:      {stats.get('admin_actions', 'N/A')}

🔔 CRITICAL ALERTS
{chr(10).join('  - ' + i for i in stats.get('critical_insights', [])) or '  None'}

{'=' * 50}
This digest was auto-generated by the Admin Panel.
"""
    return subject, body.strip()


@shared_task(name='admin_panel.tasks.admin_digest_tasks.send_admin_digest_task')
def send_admin_digest_task():
    return send_digest()