import logging
from django.db import models
from django.utils import timezone
from django.core.validators import MinValueValidator, MaxValueValidator

logger = logging.getLogger(__name__)


# ─────────────────────────────────────────────
# TaskInsight  –  daily aggregated stats per task
# ─────────────────────────────────────────────

class TaskInsight(models.Model):
    """
    Daily roll-up of task execution metrics per task name.
    Generated by analytics_tasks.daily_analytics_rollup().
    One row per (date, task_name).
    """

    date      = models.DateField(db_index=True)
    task_name = models.CharField(max_length=255, db_index=True)
    queue     = models.CharField(max_length=100, blank=True, default='')

    # Volume
    run_count     = models.PositiveIntegerField(default=0, help_text="Total executions on this date")
    success_count = models.PositiveIntegerField(default=0)
    failure_count = models.PositiveIntegerField(default=0)
    retry_count   = models.PositiveIntegerField(default=0)

    # Timing (seconds)
    avg_duration  = models.FloatField(null=True, blank=True)
    min_duration  = models.FloatField(null=True, blank=True)
    max_duration  = models.FloatField(null=True, blank=True)
    p50_duration  = models.FloatField(null=True, blank=True)
    p95_duration  = models.FloatField(null=True, blank=True)
    p99_duration  = models.FloatField(null=True, blank=True)

    # Aggregated resource usage
    total_cpu_seconds = models.FloatField(null=True, blank=True)
    avg_memory_mb     = models.FloatField(null=True, blank=True)

    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        verbose_name        = 'Task Insight'
        verbose_name_plural = 'Task Insights'
        unique_together     = [('date', 'task_name')]
        ordering            = ['-date', 'task_name']
        indexes = [
            models.Index(fields=['-date', 'task_name']),
        ]

    def __str__(self):
        return f"Insight: {self.task_name} on {self.date} ({self.run_count} runs)"

    @property
    def success_rate(self) -> float:
        if self.run_count == 0:
            return 0.0
        return round(self.success_count / self.run_count * 100, 2)

    @property
    def failure_rate(self) -> float:
        return round(100.0 - self.success_rate, 2)


# ─────────────────────────────────────────────
# TaskThroughput  –  tasks-per-minute snapshots
# ─────────────────────────────────────────────

class TaskThroughput(models.Model):
    """
    Periodic snapshots of tasks-per-minute for each queue.
    Useful for capacity planning and visualising traffic spikes.
    One row per (queue_name, snapshot_at).
    """

    class Period(models.TextChoices):
        MINUTE = '1m',  '1 Minute'
        FIVE   = '5m',  '5 Minutes'
        HOUR   = '1h',  '1 Hour'
        DAY    = '1d',  '1 Day'

    queue_name        = models.CharField(max_length=200, db_index=True)
    tasks_per_minute  = models.FloatField(
        default=0.0,
        validators=[MinValueValidator(0)],
        help_text="Throughput rate in tasks/minute",
    )
    tasks_per_hour    = models.FloatField(null=True, blank=True)
    period            = models.CharField(
        max_length=10,
        choices=Period.choices,
        default=Period.MINUTE,
        db_index=True,
    )

    # Count in this measurement window
    completed_count  = models.PositiveIntegerField(default=0)
    failed_count     = models.PositiveIntegerField(default=0)
    avg_wait_seconds = models.FloatField(null=True, blank=True)

    snapshot_at = models.DateTimeField(default=timezone.now, db_index=True)

    class Meta:
        verbose_name        = 'Task Throughput'
        verbose_name_plural = 'Task Throughputs'
        ordering            = ['-snapshot_at']
        indexes = [
            models.Index(fields=['queue_name', '-snapshot_at']),
            models.Index(fields=['period', '-snapshot_at']),
        ]

    def __str__(self):
        return (
            f"Throughput: {self.queue_name} "
            f"{self.tasks_per_minute:.1f} tasks/min "
            f"@ {self.snapshot_at:%Y-%m-%d %H:%M}"
        )


# ─────────────────────────────────────────────
# TaskFailureRate  –  failure analysis per task
# ─────────────────────────────────────────────

class TaskFailureRate(models.Model):
    """
    Aggregated failure-rate analysis per (task_name, period).
    Includes the most common error to aid debugging.
    """

    class Period(models.TextChoices):
        HOURLY  = 'hourly',  'Hourly'
        DAILY   = 'daily',   'Daily'
        WEEKLY  = 'weekly',  'Weekly'
        MONTHLY = 'monthly', 'Monthly'

    task_name   = models.CharField(max_length=255, db_index=True)
    period      = models.CharField(
        max_length=10,
        choices=Period.choices,
        default=Period.DAILY,
        db_index=True,
    )
    period_start = models.DateTimeField(db_index=True, help_text="Start of the aggregation window")
    period_end   = models.DateTimeField(help_text="End of the aggregation window")

    # Counts
    total_runs    = models.PositiveIntegerField(default=0)
    failure_count = models.PositiveIntegerField(default=0)

    # Failure percentage 0-100
    failure_pct = models.FloatField(
        default=0.0,
        validators=[MinValueValidator(0), MaxValueValidator(100)],
    )

    # Most common error in this period
    most_common_error      = models.TextField(blank=True, default='')
    most_common_error_count = models.PositiveIntegerField(default=0)

    # Secondary errors (JSON list of {error, count})
    error_breakdown = models.JSONField(default=list, blank=True)

    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        verbose_name        = 'Task Failure Rate'
        verbose_name_plural = 'Task Failure Rates'
        unique_together     = [('task_name', 'period', 'period_start')]
        ordering            = ['-period_start', 'task_name']
        indexes = [
            models.Index(fields=['task_name', 'period', '-period_start']),
            models.Index(fields=['-failure_pct']),
        ]

    def __str__(self):
        return (
            f"FailureRate: {self.task_name} "
            f"[{self.period}] {self.failure_pct:.1f}% "
            f"{self.period_start:%Y-%m-%d}"
        )


# ─────────────────────────────────────────────
# TaskCostEstimate  –  compute cost per task
# ─────────────────────────────────────────────

class TaskCostEstimate(models.Model):
    """
    Estimated compute cost per task execution.
    Populated by TaskCostService based on resource usage logs.
    One row per task_name (latest estimate).
    """

    class Currency(models.TextChoices):
        USD = 'USD', 'US Dollar'
        EUR = 'EUR', 'Euro'
        GBP = 'GBP', 'British Pound'

    task_name = models.CharField(
        max_length=255,
        unique=True,
        db_index=True,
        help_text="Dotted Python path to the Celery task",
    )

    # Resource averages (from TaskPerformanceLog)
    avg_cpu_seconds = models.FloatField(
        default=0.0,
        validators=[MinValueValidator(0)],
        help_text="Average CPU time per execution in seconds",
    )
    avg_memory_mb   = models.FloatField(
        default=0.0,
        validators=[MinValueValidator(0)],
        help_text="Average peak memory per execution in MB",
    )
    avg_wall_seconds = models.FloatField(
        default=0.0,
        validators=[MinValueValidator(0)],
        help_text="Average wall-clock execution time in seconds",
    )

    # Cost per single execution (in USD or configured currency)
    cost_per_run = models.DecimalField(
        max_digits=12,
        decimal_places=8,
        default=0,
        help_text="Estimated monetary cost per single execution",
    )
    currency = models.CharField(
        max_length=3,
        choices=Currency.choices,
        default=Currency.USD,
    )

    # Pricing model used for calculation
    cpu_cost_per_second    = models.DecimalField(max_digits=12, decimal_places=8, default=0)
    memory_cost_per_mb_sec = models.DecimalField(max_digits=12, decimal_places=8, default=0)

    # Volume context for the estimate
    sample_size         = models.PositiveIntegerField(
        default=0,
        help_text="Number of executions used for this estimate",
    )
    estimation_period   = models.CharField(
        max_length=50,
        blank=True,
        default='last_7_days',
    )

    # Monthly projection
    runs_per_day_avg    = models.FloatField(null=True, blank=True)
    monthly_cost_est    = models.DecimalField(
        max_digits=12,
        decimal_places=4,
        null=True,
        blank=True,
        help_text="Projected monthly cost based on current run frequency",
    )

    calculated_at = models.DateTimeField(default=timezone.now)
    created_at    = models.DateTimeField(auto_now_add=True)
    updated_at    = models.DateTimeField(auto_now=True)

    class Meta:
        verbose_name        = 'Task Cost Estimate'
        verbose_name_plural = 'Task Cost Estimates'
        ordering            = ['-cost_per_run']
        indexes = [
            models.Index(fields=['-cost_per_run']),
        ]

    def __str__(self):
        return (
            f"CostEst: {self.task_name} "
            f"${self.cost_per_run}/run "
            f"(avg {self.avg_wall_seconds:.1f}s)"
        )
