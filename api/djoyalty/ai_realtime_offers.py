            (TRIGGER_NEAR_TIER,       'Near Tier Upgrade'),
            (TRIGGER_POINTS_EXPIRING, 'Points Expiring'),
            (TRIGGER_POST_PURCHASE,   'Post Purchase'),
            (TRIGGER_MILESTONE,       'Milestone Reached'),
            (TRIGGER_CHURN_RISK,      'Churn Risk'),
            (TRIGGER_WINBACK,         'Win-back'),
