import logging
from decimal import Decimal
from typing import Dict, List, Optional
from django.db.models import Sum, Count, Avg, F, Q
from django.utils import timezone
from datetime import timedelta

logger = logging.getLogger(__name__)


class ReferralAnalytics:
    """
    Referral-specific analytics and reporting.
    """

    # ── Funnel Analysis ───────────────────────────────────────────────────────

    @staticmethod
    def get_referral_funnel(days: int = 30, tenant=None) -> Dict:
        """
        Referral conversion funnel:
        Link clicks → Signups → Active users → Commission earners
        """
        from api.referral.models import (
            ReferralCode, Referral, ReferralEarning
        )
        cutoff = timezone.now() - timedelta(days=days)
        qs_filter = Q(created_at__gte=cutoff)

        total_clicks     = ReferralCode.objects.filter(
            **({'tenant': tenant} if tenant else {})
        ).aggregate(t=Sum('clicks'))['t'] or 0
        unique_clicks    = ReferralCode.objects.aggregate(t=Sum('unique_clicks'))['t'] or 0
        total_signups    = Referral.objects.filter(qs_filter).count()
        active_referrals = Referral.objects.filter(
            qs_filter, is_suspicious=False
        ).count()
        commission_earners = ReferralEarning.objects.filter(
            created_at__gte=cutoff
        ).values('referred_user').distinct().count()

        def pct(a, b):
            return round(a / b * 100, 1) if b else 0.0

        return {
            'period_days':          days,
            'total_clicks':         total_clicks,
            'unique_clicks':        unique_clicks,
            'total_signups':        total_signups,
            'active_referrals':     active_referrals,
            'commission_earners':   commission_earners,
            'funnel': {
                'click_to_signup':      pct(total_signups, unique_clicks),
                'signup_to_active':     pct(active_referrals, total_signups),
                'active_to_earner':     pct(commission_earners, active_referrals),
                'overall_conversion':   pct(commission_earners, total_clicks),
            },
        }

    @staticmethod
    def get_cohort_data(cohort_months: int = 6) -> List[Dict]:
        """
        Cohort analysis: for users referred in month M,
        how much commission did they generate in M, M+1, M+2, etc.
        """
        from api.referral.models import Referral, ReferralEarning
        today = timezone.now().date()
        cohorts = []

        for i in range(cohort_months, 0, -1):
            cohort_start = (today.replace(day=1) - timedelta(days=i * 30)).replace(day=1)
            import calendar
            cohort_end = cohort_start.replace(
                day=calendar.monthrange(cohort_start.year, cohort_start.month)[1]
            )

            # Users referred in this cohort month
            cohort_users = Referral.objects.filter(
                created_at__date__range=(cohort_start, cohort_end)
            ).values_list('referred_user_id', flat=True)

            cohort_size = len(set(cohort_users))
            if cohort_size == 0:
                continue

            # Commission generated by these users
            commission = ReferralEarning.objects.filter(
                referred_user_id__in=cohort_users,
                status='released',
            ).aggregate(t=Sum('source_amount'))['t'] or Decimal('0')

            cohorts.append({
                'month':           cohort_start.strftime('%Y-%m'),
                'cohort_size':     cohort_size,
                'total_commission':float(commission),
                'avg_per_user':    float(commission / cohort_size) if cohort_size else 0,
            })

        return cohorts

    @staticmethod
    def get_channel_attribution(days: int = 30) -> List[Dict]:
        """
        Which referral channels (social, email, QR) drive the most conversions?
        """
        from api.referral.models import ReferralSocialShare
        channels = ReferralSocialShare.objects.values('platform').annotate(
            total_shares=Sum('share_count'),
            total_clicks=Sum('click_count'),
            conversions=Sum('convert_count'),
        ).order_by('-conversions')
        return list(channels)

    @staticmethod
    def get_top_referrers_by_ltv(limit: int = 10) -> List[Dict]:
        """
        Referrers whose referred users have highest total LTV.
        """
        from api.referral.models import ReferralLTV
        return list(
            ReferralLTV.objects.values('referred_by__username').annotate(
                total_ltv=Sum('lifetime_value'),
                user_count=Count('id'),
                avg_ltv=Avg('lifetime_value'),
            ).order_by('-total_ltv')[:limit]
        )

    @staticmethod
    def get_campaign_performance(campaign_id: int = None) -> List[Dict]:
        """
        Campaign-level performance stats.
        """
        from api.referral.models import ReferralCampaign, CommissionLog
        campaigns = ReferralCampaign.objects.all()
        if campaign_id:
            campaigns = campaigns.filter(id=campaign_id)

        results = []
        for campaign in campaigns:
            commissions = CommissionLog.objects.filter(campaign=campaign)
            results.append({
                'id':            campaign.id,
                'name':          campaign.name,
                'multiplier':    float(campaign.bonus_multiplier),
                'referrals':     campaign.current_referrals,
                'spend':         float(campaign.current_spend),
                'total_paid':    float(commissions.filter(
                    status='released').aggregate(t=Sum('amount'))['t'] or 0),
                'avg_commission':float(commissions.filter(
                    status='released').aggregate(t=Avg('amount'))['t'] or 0),
                'start_date':    campaign.start_date.isoformat(),
                'end_date':      campaign.end_date.isoformat(),
                'is_active':     campaign.is_active,
            })
        return results

    @staticmethod
    def get_geo_breakdown() -> List[Dict]:
        """
        Breakdown of referrals and commissions by country.
        """
        from api.referral.models import GeoCommissionRate, Referral

        # Get countries where we have geo rates defined
        countries = GeoCommissionRate.objects.filter(is_active=True).values(
            'country_code', 'country_name', 'level1_rate'
        )
        return list(countries)

    @staticmethod
    def get_time_series(metric: str = 'referrals', days: int = 30) -> List[Dict]:
        """
        Time series data for charts.
        metric: 'referrals', 'commission', 'clicks'
        """
        from api.referral.models import Referral, CommissionLog, ReferralCode
        today = timezone.now().date()
        data = []

        for i in range(days, 0, -1):
            day = today - timedelta(days=i)

            if metric == 'referrals':
                value = Referral.objects.filter(created_at__date=day).count()
            elif metric == 'commission':
                value = float(
                    CommissionLog.objects.filter(
                        created_at__date=day, status='released'
                    ).aggregate(t=Sum('amount'))['t'] or 0
                )
            elif metric == 'clicks':
                # Approximate from referral code aggregate
                value = Referral.objects.filter(created_at__date=day).count()
            else:
                value = 0

            data.append({'date': str(day), 'value': value})

        return data