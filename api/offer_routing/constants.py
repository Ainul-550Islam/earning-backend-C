class _EnumStr(str):
    @property
    def value(self):
        return str(self)

class _IntegEnumMeta(type):
    def __iter__(cls):
        return (v for k, v in vars(cls).items()
                if not k.startswith("_") and isinstance(v, _EnumStr))
    def __contains__(cls, item):
        return any(v == item for k, v in vars(cls).items()
                   if not k.startswith("_") and isinstance(v, _EnumStr))

class IntegrationType(metaclass=_IntegEnumMeta):
    WEBHOOK = _EnumStr("webhook")
    API = _EnumStr("api")
    DATABASE = _EnumStr("database")
    MESSAGE_QUEUE = _EnumStr("message_queue")
    FILE = _EnumStr("file")

class IntegrationStatus(metaclass=_IntegEnumMeta):
    ACTIVE = _EnumStr("active")
    INACTIVE = _EnumStr("inactive")
    ERROR = _EnumStr("error")
    PENDING = _EnumStr("pending")
    NOT_FOUND = _EnumStr("not_found")

class IntegrationPriority(metaclass=_IntegEnumMeta):
    LOW = _EnumStr("low")
    MEDIUM = _EnumStr("medium")
    HIGH = _EnumStr("high")

class IntegrationEvent(metaclass=_IntegEnumMeta):
    REGISTERED = _EnumStr("integration.registered")
