"""
Storage Adapter Monitoring Module
Provides real-time monitoring and alerting for storage adapters.
"""

import logging
import threading
import time
from typing import Dict, Any, List, Callable, Optional
from datetime import datetime, timedelta
from dataclasses import dataclass
from .health_check import StorageHealthChecker, HealthCheckResult

logger = logging.getLogger(__name__)


@dataclass
class MonitoringConfig:
    """Configuration for storage monitoring."""
    check_interval_seconds: int = 60
    alert_threshold_ms: float = 5000.0
    consecutive_failures_for_alert: int = 3
    enable_continuous_monitoring: bool = False
    alert_callbacks: List[Callable] = None
    
    def __post_init__(self):
        if self.alert_callbacks is None:
            self.alert_callbacks = []


@dataclass
class MonitoringAlert:
    """Alert generated by storage monitoring."""
    adapter_type: str
    alert_type: str
    message: str
    severity: str
    timestamp: datetime
    response_time_ms: float
    consecutive_failures: int
    
    def to_dict(self) -> Dict[str, Any]:
        """Convert alert to dictionary."""
        return {
            'adapter_type': self.adapter_type,
            'alert_type': self.alert_type,
            'message': self.message,
            'severity': self.severity,
            'timestamp': self.timestamp.isoformat(),
            'response_time_ms': self.response_time_ms,
            'consecutive_failures': self.consecutive_failures
        }


class StorageMonitor:
    """
    Real-time monitor for storage adapters.
    Provides continuous monitoring, alerting, and metrics collection.
    """
    
    def __init__(self, config: MonitoringConfig = None):
        """Initialize storage monitor."""
        self.config = config or MonitoringConfig()
        self.health_checker = StorageHealthChecker()
        self.monitoring_active = False
        self.monitoring_thread = None
        self.alerts: List[MonitoringAlert] = []
        self.consecutive_failures: Dict[str, int] = {}
        self.last_check_time: Dict[str, datetime] = {}
        self.metrics: Dict[str, Dict[str, Any]] = {}
        
        logger.info("Storage monitor initialized")
    
    def start_monitoring(self, storage_configs: Dict[str, Dict[str, Any]]):
        """
        Start continuous monitoring of storage adapters.
        
        Args:
            storage_configs: Configuration for each storage type
        """
        if self.monitoring_active:
            logger.warning("Monitoring is already active")
            return
        
        self.monitoring_active = True
        self.storage_configs = storage_configs
        
        if self.config.enable_continuous_monitoring:
            self.monitoring_thread = threading.Thread(
                target=self._continuous_monitoring_loop,
                daemon=True
            )
            self.monitoring_thread.start()
            logger.info(f"Started continuous monitoring with {self.config.check_interval_seconds}s interval")
        else:
            logger.info("Continuous monitoring disabled")
    
    def stop_monitoring(self):
        """Stop continuous monitoring."""
        if not self.monitoring_active:
            return
        
        self.monitoring_active = False
        
        if self.monitoring_thread and self.monitoring_thread.is_alive():
            self.monitoring_thread.join(timeout=5)
        
        logger.info("Storage monitoring stopped")
    
    def check_all_adapters(self, storage_configs: Dict[str, Dict[str, Any]] = None) -> List[HealthCheckResult]:
        """
        Perform health check on all configured adapters.
        
        Args:
            storage_configs: Configuration for each storage type
            
        Returns:
            List[HealthCheckResult]: Health check results
        """
        configs = storage_configs or getattr(self, 'storage_configs', {})
        return self.health_checker.check_all_adapters(configs)
    
    def check_single_adapter(self, storage_type: str, config: Dict[str, Any] = None) -> HealthCheckResult:
        """
        Perform health check on a single adapter.
        
        Args:
            storage_type: Type of storage adapter
            config: Storage configuration
            
        Returns:
            HealthCheckResult: Health check result
        """
        return self.health_checker.check_adapter_health(storage_type, config)
    
    def get_monitoring_status(self) -> Dict[str, Any]:
        """
        Get current monitoring status.
        
        Returns:
            Dict: Monitoring status information
        """
        return {
            'monitoring_active': self.monitoring_active,
            'config': {
                'check_interval_seconds': self.config.check_interval_seconds,
                'alert_threshold_ms': self.config.alert_threshold_ms,
                'consecutive_failures_for_alert': self.config.consecutive_failures_for_alert,
                'enable_continuous_monitoring': self.config.enable_continuous_monitoring
            },
            'consecutive_failures': self.consecutive_failures.copy(),
            'last_check_times': self.last_check_time.copy(),
            'total_alerts': len(self.alerts),
            'recent_alerts': [alert.to_dict() for alert in self.alerts[-10:]]
        }
    
    def get_adapter_metrics(self, storage_type: str) -> Dict[str, Any]:
        """
        Get metrics for a specific adapter.
        
        Args:
            storage_type: Type of storage adapter
            
        Returns:
            Dict: Adapter metrics
        """
        return self.metrics.get(storage_type, {})
    
    def get_all_metrics(self) -> Dict[str, Dict[str, Any]]:
        """
        Get metrics for all adapters.
        
        Returns:
            Dict: All adapter metrics
        """
        return self.metrics.copy()
    
    def get_recent_alerts(self, limit: int = 50, severity: str = None) -> List[MonitoringAlert]:
        """
        Get recent monitoring alerts.
        
        Args:
            limit: Maximum number of alerts to return
            severity: Filter by severity (critical, warning, info)
            
        Returns:
            List[MonitoringAlert]: Recent alerts
        """
        alerts = self.alerts
        
        if severity:
            alerts = [a for a in alerts if a.severity == severity]
        
        return alerts[-limit:] if len(alerts) > limit else alerts
    
    def clear_alerts(self, storage_type: str = None):
        """
        Clear monitoring alerts.
        
        Args:
            storage_type: Clear alerts for specific adapter type (optional)
        """
        if storage_type:
            self.alerts = [a for a in self.alerts if a.adapter_type != storage_type]
            if storage_type in self.consecutive_failures:
                del self.consecutive_failures[storage_type]
        else:
            self.alerts.clear()
            self.consecutive_failures.clear()
        
        logger.info(f"Cleared alerts for {storage_type or 'all adapters'}")
    
    def add_alert_callback(self, callback: Callable[[MonitoringAlert], None]):
        """
        Add alert callback function.
        
        Args:
            callback: Function to call when alert is generated
        """
        self.config.alert_callbacks.append(callback)
        logger.info("Added alert callback")
    
    def _continuous_monitoring_loop(self):
        """
        Main monitoring loop for continuous health checks.
        """
        logger.info("Starting continuous monitoring loop")
        
        while self.monitoring_active:
            try:
                # Perform health checks
                results = self.check_all_adapters()
                
                # Process results and generate alerts
                self._process_health_results(results)
                
                # Update metrics
                self._update_metrics(results)
                
                # Sleep until next check
                time.sleep(self.config.check_interval_seconds)
                
            except Exception as e:
                logger.error(f"Error in monitoring loop: {e}")
                time.sleep(self.config.check_interval_seconds)
    
    def _process_health_results(self, results: List[HealthCheckResult]):
        """
        Process health check results and generate alerts.
        
        Args:
            results: Health check results from all adapters
        """
        for result in results:
            adapter_type = result.adapter_type
            
            # Update consecutive failures counter
            if result.is_healthy:
                self.consecutive_failures[adapter_type] = 0
            else:
                self.consecutive_failures[adapter_type] = self.consecutive_failures.get(adapter_type, 0) + 1
            
            # Check for alert conditions
            self._check_alert_conditions(result)
            
            # Update last check time
            self.last_check_time[adapter_type] = result.last_check
    
    def _check_alert_conditions(self, result: HealthCheckResult):
        """
        Check if alert conditions are met and generate alerts.
        
        Args:
            result: Health check result to evaluate
        """
        adapter_type = result.adapter_type
        consecutive_failures = self.consecutive_failures.get(adapter_type, 0)
        
        # Check response time threshold
        if result.response_time_ms > self.config.alert_threshold_ms:
            self._generate_alert(
                adapter_type=adapter_type,
                alert_type='response_time',
                message=f"Response time {result.response_time_ms:.2f}ms exceeds threshold {self.config.alert_threshold_ms}ms",
                severity='warning',
                response_time_ms=result.response_time_ms,
                consecutive_failures=consecutive_failures
            )
        
        # Check consecutive failures
        if consecutive_failures >= self.config.consecutive_failures_for_alert:
            self._generate_alert(
                adapter_type=adapter_type,
                alert_type='consecutive_failures',
                message=f"{consecutive_failures} consecutive health check failures",
                severity='critical',
                response_time_ms=result.response_time_ms,
                consecutive_failures=consecutive_failures
            )
        
        # Check if adapter is unhealthy
        if not result.is_healthy:
            self._generate_alert(
                adapter_type=adapter_type,
                alert_type='unhealthy',
                message=f"Storage adapter is unhealthy: {result.error_message}",
                severity='critical',
                response_time_ms=result.response_time_ms,
                consecutive_failures=consecutive_failures
            )
    
    def _generate_alert(self, adapter_type: str, alert_type: str, message: str, 
                      severity: str, response_time_ms: float, consecutive_failures: int):
        """
        Generate and store a monitoring alert.
        
        Args:
            adapter_type: Type of storage adapter
            alert_type: Type of alert
            message: Alert message
            severity: Alert severity
            response_time_ms: Response time in milliseconds
            consecutive_failures: Number of consecutive failures
        """
        alert = MonitoringAlert(
            adapter_type=adapter_type,
            alert_type=alert_type,
            message=message,
            severity=severity,
            timestamp=datetime.now(),
            response_time_ms=response_time_ms,
            consecutive_failures=consecutive_failures
        )
        
        self.alerts.append(alert)
        
        # Call alert callbacks
        for callback in self.config.alert_callbacks:
            try:
                callback(alert)
            except Exception as e:
                logger.error(f"Error in alert callback: {e}")
        
        logger.warning(f"Generated {severity} alert for {adapter_type}: {message}")
    
    def _update_metrics(self, results: List[HealthCheckResult]):
        """
        Update metrics based on health check results.
        
        Args:
            results: Health check results
        """
        for result in results:
            adapter_type = result.adapter_type
            
            if adapter_type not in self.metrics:
                self.metrics[adapter_type] = {
                    'total_checks': 0,
                    'successful_checks': 0,
                    'failed_checks': 0,
                    'average_response_time': 0.0,
                    'min_response_time': float('inf'),
                    'max_response_time': 0.0,
                    'last_healthy': None,
                    'uptime_percentage': 0.0
                }
            
            metrics = self.metrics[adapter_type]
            metrics['total_checks'] += 1
            
            if result.is_healthy:
                metrics['successful_checks'] += 1
                metrics['last_healthy'] = result.last_check
            else:
                metrics['failed_checks'] += 1
            
            # Update response time metrics
            response_time = result.response_time_ms
            metrics['average_response_time'] = (
                (metrics['average_response_time'] * (metrics['total_checks'] - 1) + response_time) / 
                metrics['total_checks']
            )
            metrics['min_response_time'] = min(metrics['min_response_time'], response_time)
            metrics['max_response_time'] = max(metrics['max_response_time'], response_time)
            
            # Calculate uptime percentage
            if metrics['total_checks'] > 0:
                metrics['uptime_percentage'] = (metrics['successful_checks'] / metrics['total_checks']) * 100


# Convenience functions
def create_monitor(config: MonitoringConfig = None) -> StorageMonitor:
    """
    Create a new storage monitor instance.
    
    Args:
        config: Monitoring configuration
        
    Returns:
        StorageMonitor: Monitor instance
    """
    return StorageMonitor(config)


def quick_health_check_with_alerts(storage_configs: Dict[str, Dict[str, Any]], 
                               alert_threshold_ms: float = 5000.0) -> Dict[str, Any]:
    """
    Perform quick health check with automatic alerting.
    
    Args:
        storage_configs: Configuration for each storage type
        alert_threshold_ms: Response time threshold for alerts
        
    Returns:
        Dict: Health check results with any alerts generated
    """
    config = MonitoringConfig(
        check_interval_seconds=0,  # Single check
        alert_threshold_ms=alert_threshold_ms,
        consecutive_failures_for_alert=1
    )
    
    monitor = StorageMonitor(config)
    results = monitor.check_all_adapters(storage_configs)
    
    return {
        'health_results': [result.__dict__ for result in results],
        'alerts': [alert.to_dict() for alert in monitor.get_recent_alerts()],
        'summary': monitor.get_monitoring_status()
    }
